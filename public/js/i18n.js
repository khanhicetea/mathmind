const DICTS = { en, vi, fr, ja, es };

export function detectLang() {
  for (const l of navigator.languages || [navigator.language || 'en']) {
    const code = String(l).toLowerCase().split('-')[0];
    if (DICTS[code]) return code;
  }
  return 'en';
}

let lang = 'en';
export const getLang = () => lang;
/** `pref` is the saved setting: a language code, or '' for the browser's language. */
export function setLang(pref) {
  lang = DICTS[pref] ? pref : detectLang();
  document.documentElement.lang = lang;
}

export function t(key, vars = {}) {
  let s = DICTS[lang][key] ?? en[key] ?? key;
  if (s && typeof s === 'object' && !Array.isArray(s)) s = s[new Intl.PluralRules(lang).select(vars.n)] ?? s.other;
  return typeof s === 'string' ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

/** Translate static markup: data-i18n (text), data-i18n-html, data-i18n-aria, data-i18n-ph (placeholder). */
export function translateDom(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
}
